# ==========================================
# TUPLE SLICING
# ==========================================

numbers = (10, 20, 30, 40, 50, 60)


# Syntax:
#
# tuple[start : stop : step]


# ------------------------------------------
# 1. Basic Slicing
# ------------------------------------------

print(numbers[1:4])

# Output:
# (20, 30, 40)


# ------------------------------------------
# 2. Start from Beginning
# ------------------------------------------

print(numbers[:3])

# Output:
# (10, 20, 30)


# ------------------------------------------
# 3. Go Until End
# ------------------------------------------

print(numbers[2:])

# Output:
# (30, 40, 50, 60)


# ------------------------------------------
# 4. Copy Entire Tuple
# ------------------------------------------

print(numbers[:])

# Output:
# (10, 20, 30, 40, 50, 60)


# ------------------------------------------
# 5. Using Step
# ------------------------------------------

print(numbers[::2])

# Output:
# (10, 30, 50)


# ------------------------------------------
# 6. Every Third Element
# ------------------------------------------

print(numbers[::3])

# Output:
# (10, 40)


# ------------------------------------------
# 7. Reverse Tuple
# ------------------------------------------

print(numbers[::-1])

# Output:
# (60, 50, 40, 30, 20, 10)


# ------------------------------------------
# 8. Reverse with Step
# ------------------------------------------

print(numbers[5:1:-1])

# Output:
# (60, 50, 40, 30)


# ------------------------------------------
# 9. Negative Slicing
# ------------------------------------------

print(numbers[-4:-1])

# Output:
# (30, 40, 50)


# ------------------------------------------
# 10. String Tuple Slicing
# ------------------------------------------

students = (
    "Santhosh",
    "Rahul",
    "Kiran",
    "Arun",
    "Ravi"
)

print(students[1:4])

# Output:
# ('Rahul', 'Kiran', 'Arun')


# ------------------------------------------
# 11. Slicing Does Not Modify Tuple
# ------------------------------------------

numbers = (10, 20, 30, 40, 50)

new_tuple = numbers[1:4]

print("Original:", numbers)
print("Sliced:", new_tuple)