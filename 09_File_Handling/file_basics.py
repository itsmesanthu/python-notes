# ============================================================
# FILE HANDLING
# ============================================================
# File handling allows Python programs to create, read,
# write, and modify files.
#
# Main steps:
#
# 1. Open the file
# 2. Perform an operation
# 3. Close the file
#
# Python provides the open() function for working with files.
#
# Syntax:
#
# open(filename, mode)
#
# Common modes:
#
# "r"  -> Read
# "w"  -> Write
# "a"  -> Append
# "x"  -> Create
# "b"  -> Binary mode
# ============================================================