
# ============================================================
# NUMPY OPERATIONS
# ============================================================

import numpy as np


# ============================================================
# 1. ADDITION
# ============================================================

arr = np.array([10, 20, 30])

print(arr + 5)

# Output:
# [15 25 35]


# ============================================================
# 2. SUBTRACTION
# ============================================================

arr = np.array([10, 20, 30])

print(arr - 5)

# Output:
# [ 5 15 25]


# ============================================================
# 3. MULTIPLICATION
# ============================================================

arr = np.array([2, 4, 6])

print(arr * 3)

# Output:
# [ 6 12 18]


# ============================================================
# 4. DIVISION
# ============================================================

arr = np.array([10, 20, 30])

print(arr / 10)

# Output:
# [1. 2. 3.]


# ============================================================
# 5. OPERATIONS BETWEEN ARRAYS
# ============================================================

arr1 = np.array([10, 20, 30])
arr2 = np.array([1, 2, 3])

print(arr1 + arr2)
print(arr1 - arr2)
print(arr1 * arr2)
print(arr1 / arr2)

# Output:
# [11 22 33]
# [ 9 18 27]
# [10 40 90]
# [10. 10. 10.]


# ============================================================
# 6. SUM
# ============================================================

arr = np.array([10, 20, 30, 40])

print(np.sum(arr))

# Output:
# 100


# ============================================================
# 7. MINIMUM AND MAXIMUM
# ============================================================

arr = np.array([10, 5, 40, 20])

print(np.min(arr))
print(np.max(arr))

# Output:
# 5
# 40


# ============================================================
# 8. MEAN
# ============================================================

arr = np.array([10, 20, 30, 40])

print(np.mean(arr))

# Output:
# 25.0


# ============================================================
# 9. MEDIAN
# ============================================================

arr = np.array([10, 20, 30, 40, 50])

print(np.median(arr))

# Output:
# 30.0


# ============================================================
# 10. STANDARD DEVIATION
# ============================================================

arr = np.array([10, 20, 30, 40, 50])

print(np.std(arr))

# Output: approximately 14.14


# ============================================================
# 11. COMPARISON OPERATIONS
# ============================================================

arr = np.array([10, 20, 30, 40])

print(arr > 20)

# Output:
# [False False  True  True]


# ============================================================
# 12. CONDITIONAL OPERATIONS
# ============================================================

arr = np.array([10, 20, 30, 40, 50])

print(arr[arr > 25])

# Output:
# [30 40 50]


# ============================================================
# 13. ROUNDING VALUES
# ============================================================

arr = np.array([1.234, 2.567, 3.891])

print(np.round(arr, 2))

# Output:
# [1.23 2.57 3.89]


