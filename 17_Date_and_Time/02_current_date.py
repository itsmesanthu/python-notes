# ============================================================
# CURRENT DATE
# ============================================================

from datetime import date


# ============================================================
# 1. GET TODAY'S DATE
# ============================================================

today = date.today()

print(today)


# Example output:
# 2026-09-23


# ============================================================
# 2. GET YEAR
# ============================================================

today = date.today()

print(today.year)


# Output:
# 2026


# ============================================================
# 3. GET MONTH
# ============================================================

today = date.today()

print(today.month)


# Output:
# 9


# ============================================================
# 4. GET DAY
# ============================================================

today = date.today()

print(today.day)


# Output:
# 23


# ============================================================
# 5. PRINT DATE INFORMATION
# ============================================================

today = date.today()

print("Year:", today.year)
print("Month:", today.month)
print("Day:", today.day)


# ============================================================
# 6. CREATE A SPECIFIC DATE
# ============================================================

birthday = date(2004, 9, 18)

print(birthday)


# Output:
# 2004-09-18


# ============================================================
# 7. COMPARE DATES
# ============================================================

date1 = date(2026, 9, 23)
date2 = date(2026, 12, 25)

if date1 < date2:
    print("Date 1 is earlier")


# Output:
# Date 1 is earlier


