# ============================================================
# TIME OBJECTS
# ============================================================

from datetime import time


# ============================================================
# 1. CREATE TIME OBJECT
# ============================================================

my_time = time(10, 30, 45)

print(my_time)


# Output:
# 10:30:45


# ============================================================
# 2. CREATE TIME WITH MICROSECONDS
# ============================================================

my_time = time(
    10,
    30,
    45,
    500000
)

print(my_time)


# Output:
# 10:30:45.500000


# ============================================================
# 3. ACCESS HOUR
# ============================================================

my_time = time(10, 30, 45)

print(my_time.hour)


# Output:
# 10


# ============================================================
# 4. ACCESS MINUTE
# ============================================================

print(my_time.minute)


# Output:
# 30


# ============================================================
# 5. ACCESS SECOND
# ============================================================

print(my_time.second)


# Output:
# 45


# ============================================================
# 6. ACCESS MICROSECOND
# ============================================================

my_time = time(10, 30, 45, 500000)

print(my_time.microsecond)


# Output:
# 500000


# ============================================================
# 7. CREATE MIDNIGHT
# ============================================================

midnight = time(0, 0, 0)

print(midnight)


# Output:
# 00:00:00


# ============================================================
# 8. CREATE NOON
# ============================================================

noon = time(12, 0, 0)

print(noon)


# Output:
# 12:00:00


# ============================================================
# QUICK REVISION
# ============================================================

