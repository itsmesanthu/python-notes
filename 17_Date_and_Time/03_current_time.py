# ============================================================
# CURRENT TIME
# ============================================================

from datetime import datetime


# ============================================================
# 1. GET CURRENT DATE AND TIME
# ============================================================

now = datetime.now()

print(now)


# ============================================================
# 2. GET CURRENT TIME
# ============================================================

now = datetime.now()

print(now.time())


# Example:
# 17:30:15.123456


# ============================================================
# 3. GET HOUR
# ============================================================

now = datetime.now()

print(now.hour)


# ============================================================
# 4. GET MINUTE
# ============================================================

now = datetime.now()

print(now.minute)


# ============================================================
# 5. GET SECOND
# ============================================================

now = datetime.now()

print(now.second)


# ============================================================
# 6. GET MICROSECOND
# ============================================================

now = datetime.now()

print(now.microsecond)


# ============================================================
# 7. PRINT TIME INFORMATION
# ============================================================

now = datetime.now()

print("Hour:", now.hour)
print("Minute:", now.minute)
print("Second:", now.second)


# ============================================================
# 8. CREATE SPECIFIC TIME
# ============================================================

from datetime import time

my_time = time(10, 30, 45)

print(my_time)


# Output:
# 10:30:45


